-- -----------------------------------------------------------------------------
-- Function: dbo.insertinappointmenttable
-- Source: [dbo].[insertInAppointmentTable]
-- Single DML, no result set → void function.
-- Transformation:
--   CONVERT(VARCHAR(11), GETDATE(), 6) → TO_CHAR(CURRENT_DATE, 'DD Mon YYYY')
--   CONVERT(datetime, @date)           → to_timestamp(v_date, 'DD Mon YYYY HH24:MI')
--   Slot arithmetic preserved (slots < 9 → add 12 for PM hours).
-- NOTE: Original INSERT used positional VALUES; explicit column list added.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION dbo.insertinappointmenttable(
    p_pid       integer,
    p_did       integer,
    p_freeslot  integer
)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_slot  integer;
    v_date  text;
    v_datea timestamp without time zone;
BEGIN
    v_slot := p_freeslot;
    IF v_slot < 9 THEN
        v_slot := v_slot + 12;
    END IF;

    -- Build date string matching original CONVERT(VARCHAR(11), GETDATE(), 6) format
    v_date := TO_CHAR(CURRENT_DATE, 'DD Mon YYYY') || ' ' || v_slot::text || ':00';

    v_datea := to_timestamp(v_date, 'DD Mon YYYY HH24:MI');

    INSERT INTO dbo.appointment (
        doctorid, patientid, date,
        appointment_status, bill_amount, bill_status,
        doctornotification, patientnotification,
        feedbackstatus, disease, progress, prescription
    )
    VALUES (
        p_did, p_pid, v_datea,
        2, NULL, NULL,
        2, 1,
        NULL, NULL, NULL, NULL
    );
END;
$$;

