-- -----------------------------------------------------------------------------
-- Function: dbo.adddoctor
-- Source: [dbo].[AddDoctor]
-- Single result set (no SELECT returned to caller) → void function.
-- NOTE: Original INSERT INTO LoginTable/Doctor used positional VALUES.
--       Explicit column lists added per PostgreSQL best practice.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION dbo.adddoctor(
    p_name      varchar(50),
    p_email     varchar(50),
    p_password  varchar(50),
    p_birthdate date,
    p_dept      integer,
    p_gender    char(1),
    p_address   varchar(50),
    p_exp       integer,
    p_salary    integer,
    p_spec      varchar(50),
    p_phone     varchar(50),
    p_charges   integer,
    p_qual      varchar(50)
)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_id integer;
BEGIN
    INSERT INTO dbo.logintable (password, email, type)
    VALUES (p_password, p_email, 2);

    SELECT loginid INTO v_id
    FROM dbo.logintable
    WHERE email = p_email;

    INSERT INTO dbo.doctor (
        doctorid, name, phone, address, birthdate, gender,
        deptno, charges_per_visit, monthlysalary, reputeindex,
        patients_treated, qualification, specialization,
        work_experience, status
    )
    VALUES (
        v_id, p_name, p_phone, p_address, p_birthdate, p_gender,
        p_dept, p_charges, p_salary, 0,
        0, p_qual, p_spec,
        p_exp, -1
    );
END;
$$;

