-- -----------------------------------------------------------------------------
-- Function: dbo.retrievecurrentappointment
-- Source: [dbo].[RetrieveCurrentAppointment]
-- MIXED: complex logic with DML and multiple OUT parameters.
-- Multiple OUT parameters → RETURNS SETOF record with RETURN NEXT.
-- Transformation:
--   DATEPART(day/month/year, ...) → EXTRACT(... FROM ...)
--   CONVERT(VARCHAR(19), [date]) → TO_CHAR(date, 'YYYY-MM-DD HH24:MI:SS')
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION dbo.retrievecurrentappointment(
    p_pid       integer,
    OUT p_dname   varchar(30),
    OUT p_timings varchar(30),
    OUT p_count   integer
)
RETURNS SETOF record
LANGUAGE plpgsql
AS $$
DECLARE
    v_aday   integer;
    v_amonth integer;
    v_ayear  integer;
BEGIN
    IF EXISTS (
        SELECT 1 FROM dbo.appointment
        WHERE patientid = p_pid AND appointment_status = 2
    ) THEN
        -- Extract date parts of the pending appointment
        SELECT
            EXTRACT(DAY   FROM a.date)::integer,
            EXTRACT(MONTH FROM a.date)::integer,
            EXTRACT(YEAR  FROM a.date)::integer
        INTO v_aday, v_amonth, v_ayear
        FROM dbo.appointment a
        WHERE patientid = p_pid AND appointment_status = 2;

        SELECT
            d.name,
            TO_CHAR(a.date, 'YYYY-MM-DD HH24:MI:SS')
        INTO p_dname, p_timings
        FROM dbo.appointment a
        JOIN dbo.doctor d ON a.doctorid = d.doctorid
        WHERE a.patientid = p_pid AND a.appointment_status = 2;

        -- If the appointment date is not today, delete it (outdated)
        IF v_aday   != EXTRACT(DAY   FROM CURRENT_TIMESTAMP)::integer
        OR v_amonth != EXTRACT(MONTH FROM CURRENT_TIMESTAMP)::integer
        OR v_ayear  != EXTRACT(YEAR  FROM CURRENT_TIMESTAMP)::integer
        THEN
            DELETE FROM dbo.appointment
            WHERE patientid = p_pid AND appointment_status = 2;
            p_count := 3;
        ELSE
            p_count := 2;
        END IF;

    ELSE
        IF EXISTS (
            SELECT 1 FROM dbo.appointment
            WHERE patientid = p_pid AND appointment_status = 1
        ) THEN
            SELECT
                d.name,
                TO_CHAR(a.date, 'YYYY-MM-DD HH24:MI:SS')
            INTO p_dname, p_timings
            FROM dbo.appointment a
            JOIN dbo.doctor d ON a.doctorid = d.doctorid
            WHERE a.patientid = p_pid AND a.appointment_status = 1;
            p_count := 1;
        ELSE
            p_count := 0;
        END IF;
    END IF;

    RETURN NEXT;
END;
$$;

