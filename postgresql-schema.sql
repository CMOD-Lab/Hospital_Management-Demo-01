-- Function: dbo.get_doctor_profile
-- Source: [dbo].[GET_DOCTOR_PROFILE]
-- Multiple OUT parameters → RETURNS SETOF record with RETURN NEXT.
-- Rule: multiple OUT params → RETURNS SETOF record.
-- Transformation: DATEDIFF(YEAR, BirthDate, GETDATE())
--   → EXTRACT(YEAR FROM AGE(CURRENT_TIMESTAMP, birthdate))::integer
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION dbo.get_doctor_profile(
    p_did           integer,
    OUT p_name      varchar(20),
    OUT p_phone     char(15),
    OUT p_gender    varchar(2),
    OUT p_charges   double precision,
    OUT p_ri        double precision,
    OUT p_ptreated  integer,
    OUT p_qualification varchar(100),
    OUT p_specialization varchar(50),
    OUT p_worke     integer,
    OUT p_age       integer
)
RETURNS SETOF record
LANGUAGE plpgsql
AS $$
BEGIN
    SELECT
        d.name,
        d.phone,
        d.gender,
        d.charges_per_visit,
        d.reputeindex,
        d.patients_treated,
        d.qualification,
        d.specialization,
        d.work_experience,
        EXTRACT(YEAR FROM AGE(CURRENT_TIMESTAMP, d.birthdate))::integer
    INTO
        p_name, p_phone, p_gender, p_charges, p_ri,
        p_ptreated, p_qualification, p_specialization, p_worke, p_age
    FROM dbo.doctor d
    WHERE d.doctorid = p_did;

    RETURN NEXT;
END;
$$;

