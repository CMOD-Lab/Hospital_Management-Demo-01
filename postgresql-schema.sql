-- -----------------------------------------------------------------------------
-- View: dbo.department_view
-- Source: [dbo].[Department_View]
-- Transformation: SELECT TOP 20 ... ORDER BY → SELECT ... ORDER BY ... LIMIT 20
-- NOTE: PostgreSQL does not support TOP inside a plain view with ORDER BY.
--       The ORDER BY + LIMIT is preserved using a subquery.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW dbo.department_view AS
SELECT sub.id, sub.name, sub.description, sub."Number of Doctors"
FROM (
    SELECT
        department.deptno        AS id,
        department.deptname      AS name,
        department.description,
        count(department.deptno) AS "Number of Doctors"
    FROM dbo.department
    JOIN dbo.doctor ON department.deptno = doctor.deptno
    WHERE doctor.status != 0
    GROUP BY department.deptno, department.deptname, department.description
    ORDER BY department.deptno
    LIMIT 20
) sub;

-- -----------------------------------------------------------------------------
-- View: dbo.appointment_view
-- Source: [dbo].[Appointment_view]
-- Transformation: DATEDIFF(MONTH, A.Date, GETDATE()) = 0
--   → date_trunc('month', a.date) = date_trunc('month', CURRENT_TIMESTAMP)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW dbo.appointment_view AS
SELECT
    a.appointid,
    doctor.name,
    patient.patientid,
    a.date
FROM dbo.appointment a
JOIN dbo.patient ON patient.patientid = a.patientid
JOIN dbo.doctor  ON doctor.doctorid   = a.doctorid
WHERE date_trunc('month', a.date) = date_trunc('month', CURRENT_TIMESTAMP);

