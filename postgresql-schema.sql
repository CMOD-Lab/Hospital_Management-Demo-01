-- -----------------------------------------------------------------------------
-- Function: dbo.retrievefreeslots
-- Source: [dbo].[RetrieveFreeSlots]
-- MIXED: returns a result set AND has an OUT parameter (count).
-- PostgreSQL cannot mix OUT parameters with RETURNS TABLE.
-- SOLUTION: REFCURSOR pattern (Crystal Reports / external integrations active).
-- The free-slots result set is returned via ref_slots REFCURSOR.
-- The count is returned via ref_count REFCURSOR.
-- Transformation:
--   WHILE loop with DATEPART checks → generate_series + NOT EXISTS
--   fnSplitString call → replaced with direct set-returning logic
--   CAST(@tempHour AS VARCHAR) + @tempT → string formatting in SQL
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION dbo.retrievefreeslots(
    p_did           integer,
    p_pid           integer,
    OUT ref_slots   REFCURSOR,
    OUT ref_count   REFCURSOR
)
RETURNS SETOF record
LANGUAGE plpgsql
AS $$
DECLARE
    v_today date := CURRENT_DATE;
BEGIN
    -- ref_slots: returns free hour slots as formatted strings
    OPEN ref_slots FOR
        WITH hours AS (
            SELECT generate_series(9, 17) AS hr
        ),
        booked AS (
            SELECT EXTRACT(HOUR FROM a.date)::integer AS booked_hr
            FROM dbo.appointment a
            WHERE a.doctorid = p_did
              AND a.date::date = v_today
        ),
        free AS (
            SELECT h.hr
            FROM hours h
            WHERE h.hr NOT IN (SELECT booked_hr FROM booked)
              AND h.hr != 18   -- slots are 9..17 (9 AM to 5 PM, exclusive of 18)
        )
        SELECT
            CASE
                WHEN hr < 12  THEN (hr)::text          || ':00 AM'
                WHEN hr = 12  THEN '12:00 PM'
                ELSE               (hr - 12)::text     || ':00 PM'
            END AS "Free Slots"
        FROM free
        ORDER BY hr;

    -- ref_count: returns the count of free slots
    OPEN ref_count FOR
        WITH hours AS (
            SELECT generate_series(9, 17) AS hr
        ),
        booked AS (
            SELECT EXTRACT(HOUR FROM a.date)::integer AS booked_hr
            FROM dbo.appointment a
            WHERE a.doctorid = p_did
              AND a.date::date = v_today
        )
        SELECT COUNT(*) AS count
        FROM hours h
        WHERE h.hr NOT IN (SELECT booked_hr FROM booked)
          AND h.hr != 18;

    RETURN NEXT;
END;
$$;

