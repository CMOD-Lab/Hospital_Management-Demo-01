-- -----------------------------------------------------------------------------
-- Function: dbo.fnsplitstring
-- Source: [dbo].[fnSplitString]
-- Transformation: Table-valued function with WHILE loop →
--   set-returning function using regexp_split_to_table.
--   The original used CHARINDEX loop; PostgreSQL's regexp_split_to_table
--   is idiomatic and equivalent.
-- NOTE: The trailing empty token produced by a trailing delimiter is filtered
--       out to match SQL Server behaviour (SQL Server CHARINDEX loop stops
--       before the trailing empty string).
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION dbo.fnsplitstring(
    p_string    text,
    p_delimiter char(1)
)
RETURNS TABLE (splitdata text)
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT token
    FROM regexp_split_to_table(p_string, regexp_quote(p_delimiter)) AS token
    WHERE token <> '';
$$;

